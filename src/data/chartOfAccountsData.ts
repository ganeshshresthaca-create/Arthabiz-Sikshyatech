/**
 * Master Chart of Accounts (COA) Taxonomy
 * Standardized 5-Element Ledger Classification System:
 * 1. Assets (1000-1999) - Normal Balance: Debit (Dr)
 * 2. Liabilities (2000-2999) - Normal Balance: Credit (Cr)
 * 3. Equity (3000-3999) - Normal Balance: Credit (Cr)
 * 4. Income / Revenue (4000-4999) - Normal Balance: Credit (Cr)
 * 5. Expenses (5000-5999) - Normal Balance: Debit (Dr)
 */

export type AccountElement = 'Assets' | 'Liabilities' | 'Equity' | 'Income' | 'Expenses';
export type NormalBalance = 'Debit' | 'Credit';
export type FinancialStatementType = 'SoFP/BS' | 'Income Statement/SoPL';

export interface AccountHead {
  code: string;
  name: string;
  nameNepali: string;
  element: AccountElement;
  subCategory: string;
  normalBalance: NormalBalance;
  statement: FinancialStatementType;
  description: string;
  isContra?: boolean;
  contraTarget?: string;
  mcqKeyNote: string;
}

